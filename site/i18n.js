const languageKey = 'sbo-academy-language';
export let language = /^de\b/i.test(navigator.language) ? 'de' : 'en';
try {
  const saved = localStorage.getItem(languageKey);
  if (saved === 'en' || saved === 'de') language = saved;
} catch {
  // Language changes still apply in the current session.
}

export function setLanguage(value) {
  if (value !== 'en' && value !== 'de') return;
  language = value;
  try {
    localStorage.setItem(languageKey, value);
  } catch {
    // Language changes still apply in the current session.
  }
}

export function t(text) {
  if (language !== 'de' || typeof text !== 'string') return text;
  if (Object.hasOwn(germanUI, text)) return germanUI[text];
  if (Object.hasOwn(germanContent, text)) return germanContent[text];
  return text;
}

// Localize static template text before interaction handlers are attached.
export function translateView(root) {
  if (language !== 'de') return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    if (node.parentElement.closest('textarea, .work, [data-no-translate]')) continue;
    const value = node.nodeValue.trim();
    if (!value) continue;
    const translated = t(value);
    node.nodeValue = node.nodeValue.replace(value, translated);
  }
  for (const element of root.querySelectorAll('[aria-label]')) {
    element.setAttribute('aria-label', t(element.getAttribute('aria-label')));
  }
}
